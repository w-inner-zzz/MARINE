"""Export everything the static website (web/) needs into web/data/.

Run:  python export_web.py

The website cannot run Python, so this script runs every scenario with the
real backend (marine_guard) and simulator (sim) and stores the results, plus
all teaching texts, as JavaScript files. Large data is gzip-compressed and
base64-encoded so the files stay small; plain <script> tags load them, which
also works when index.html is opened straight from disk (file://).
"""

import base64
import gzip
import json
import math
import pathlib
import shutil
from dataclasses import asdict

import numpy as np

from marine_guard import ACTIONS, GuardConfig, State
from sim.analysis import detections, first_danger, path_errors
from sim.runner import Run, run_scenario, summarize
from sim.scenarios import SCENARIOS, VOYAGE_SCENARIOS
from sim.solutions import PEERS, PSEUDOLITE_SITES, SOLUTIONS
from sim.world import SATELLITE_COUNT, TRACKING_THRESHOLD_DBHZ
from teaching.briefing import briefing_blocks, further_reading
from teaching.captions import CAPTIONS, SECTION_TEXT
from teaching.decision_text import DISCLAIMER, PLAYBOOK_SOURCES, RULE_SOURCES, STATE_MEANING
from teaching.derivations import derivation_sections
from teaching.explanations import CHECK_EXPLANATIONS, SKIPPED_MEANING
from teaching.palette import palette_dict
