WEB_DATA = pathlib.Path(__file__).resolve().parent / "web" / "data"
NAV_DATA = pathlib.Path(__file__).resolve().parent / "web-navigator" / "data"
"""The bridge view gets its own, slimmer copy so that folder works on its own."""
STATES = [s.value for s in State]
VERDICTS = ["OK", "DEGRADED", "LOST", "JAMMING", "SPOOFING"]
DERIVATION_EXAMPLE = ("normal", 600)
"""Scenario and second used for the worked examples on the Derivations page."""


def packed(obj) -> str:
    """JSON -> gzip -> base64 text (decoded in the browser by util.js)."""
    raw = json.dumps(obj, separators=(",", ":")).encode()
    return base64.b64encode(gzip.compress(raw, 9)).decode()


def write_js(path: pathlib.Path, assignment: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("// Generated by export_web.py - do not edit by hand.\n" + assignment + "\n")


def r(value, digits: int):
    return None if value is None else round(float(value), digits)


# ------------------------------------------------------------ scenarios


def scenario_payload(run: Run) -> dict:
    sc = run.scenario
    rows = run.rows
    col = lambda f: [f(row) for row in rows]  # noqa: E731
    events = detections(run)
    danger = first_danger(run)
    summary = summarize(run)
    errors = path_errors(run)
    return {
        "meta": {
            "key": sc.key, "title": sc.title, "description": sc.description,
            "event_text": sc.event_text, "event_start": sc.event_start,
            "event_end": sc.event_end, "duration": sc.duration, "voyage": run.voyage,
            "fixes_enabled": sc.fixes_enabled,
        },
        "state": col(lambda w: STATES.index(w.result.state.value)),
        "verdict": col(lambda w: VERDICTS.index(w.result.verdict)),
        "lat": col(lambda w: r(w.guard_latlon[0], 6)),
        "lon": col(lambda w: r(w.guard_latlon[1], 6)),
        "unc": col(lambda w: r(w.result.uncertainty_m, 1)),
        "tlat": col(lambda w: r(w.true_latlon[0], 6)),
        "tlon": col(lambda w: r(w.true_latlon[1], 6)),
        "glat": col(lambda w: r(w.gnss_latlon[0], 6) if w.gnss_latlon else None),
        "glon": col(lambda w: r(w.gnss_latlon[1], 6) if w.gnss_latlon else None),
        "gx": col(lambda w: r(w.gnss_position[0], 1) if w.gnss_position else None),
        "gy": col(lambda w: r(w.gnss_position[1], 1) if w.gnss_position else None),
        "heading": col(lambda w: r(w.sensors.heading_deg, 1)),
        "speed": col(lambda w: r(w.sensors.speed_through_water_mps, 2)),
        "agc": col(lambda w: r(w.epoch.agc_db, 2)),
        "b_agc": col(lambda w: r(w.result.baseline_agc_db, 2)),
        "b_cn0": col(lambda w: r(w.result.baseline_cn0_dbhz, 2)),
        "b_clock": col(lambda w: r(w.result.baseline_clock_s, 4)),
        "clock": col(lambda w: r(w.epoch.gnss_time_error_s, 4)),
        "hdop": col(lambda w: r(w.result.hdop, 2)),
        "nsat": col(lambda w: w.result.satellite_count),
        "clean": col(lambda w: w.result.clean_seconds),
        "need": col(lambda w: w.result.clean_needed),
        "fixes": col(lambda w: ("radar" in w.result.fixes) + 2 * ("depth" in w.result.fixes)),
        "gerr": col(lambda w: r(w.guard_error, 1)),
        "nerr": col(lambda w: r(w.naive_error, 1)),
        "reason": col(lambda w: w.result.reason),
        # Satellites: [id, azimuth, elevation, C/N0, tracked] per second.
        "sats": col(lambda w: [[s.id, r(s.azimuth_deg, 1), r(s.elevation_deg, 1),
                                r(s.cn0_dbhz, 1), int(s.tracked)] for s in w.epoch.satellites]),
        # Checks in CHECK_ORDER: [passed (1/0/null), value, threshold, text if skipped].
        "checks": col(lambda w: [[None if c.passed is None else int(c.passed), r(c.value, 3),
                                  r(c.threshold, 3), c.text if c.passed is None else None]
                                 for c in w.result.checks]),
        "detections": [{"t": d.t, "lat": d.latlon[0], "lon": d.latlon[1],
                        "state": d.state.value, "reason": d.reason} for d in events],
        "danger": None if danger is None else {
            "t": danger.t, "lat": danger.latlon[0], "lon": danger.latlon[1],
            "what": danger.what, "off_by_m": danger.off_by_m},
        "summary": asdict(summary),
        "path_errors": asdict(errors),
    }


def comparison_row(run: Run) -> dict:
    s, paths = summarize(run), path_errors(run)

    def seconds(v):
        return "-" if v is None else f"{v:.0f} s"

    return {
        "Scenario": run.scenario.title,
        "First detection": seconds(s.detection_s),
        "Back to TRUSTED after event": seconds(s.back_to_trusted_s),
        "Worst error, guard (m)": round(s.worst_guard_error_m, 1),
        "Worst error, naive GNSS (m)": round(s.worst_naive_error_m, 1),
        "Red path worst (m)": round(paths.red_worst_m, 1),
        "Green path worst (m)": round(paths.green_worst_m, 1),
    }


# ----------------------------------------------------------------- chart


def chart_payload(run: Run) -> dict:
    """Depth grid (255 = land) for the route map and a coarse Baltic land mask."""
    from sim.baltic import OVERVIEW_BOUNDS, OVERVIEW_STEP_DEG, overview_land

    chart = run.chart
    grid = chart.grid
    step = 2  # about 560 m cells: plenty for the map background
    depth = np.where(chart.land, 255, np.clip(np.round(grid.depth), 0, 254))[::step, ::step]
    lats, lons = grid.cell_centres()
    o_lats, o_lons, o_land = overview_land()
    return {
        "route": {
            "lat0": float(lats[0]), "lon0": float(lons[0]),
            "dlat": grid.dlat * step, "dlon": grid.dlon * step,
            "depth": depth.astype(int).tolist(),
            "synthetic": grid.synthetic, "source": grid.source,
        },
        "overview": {
            "lat0": OVERVIEW_BOUNDS[0], "lon0": OVERVIEW_BOUNDS[2], "step": OVERVIEW_STEP_DEG,
            "land": ["".join("1" if v else "0" for v in row) for row in o_land],
        },
    }


# --------------------------------------------------------------- content


def content_payload(cfg: GuardConfig, example: Run) -> dict:
    def blocks(b):
        return [dict(x) for x in b]

    example_row = example.rows[DERIVATION_EXAMPLE[1]]
    return {
        "config": asdict(cfg),
        "palette": palette_dict(),
        "tracking_threshold_dbhz": TRACKING_THRESHOLD_DBHZ,
        "states": STATES,
        "verdicts": VERDICTS,
        "state_meaning": {s.value: text for s, text in STATE_MEANING.items()},
        "actions": {s.value: a.to_dict() for s, a in ACTIONS.items()},
        "checks": [{"name": c.name, "verdict_if_failed": c.verdict_if_failed}
                   for c in example_row.result.checks],
        "check_explanations": CHECK_EXPLANATIONS,
        "skipped_meaning": SKIPPED_MEANING,
        "captions": CAPTIONS,
        "section_text": SECTION_TEXT,
        "disclaimer": DISCLAIMER,
        "rule_sources": RULE_SOURCES,
        "playbook_sources": [list(p) for p in PLAYBOOK_SOURCES],
        "sources": {k: {"title": t, "url": u} for k, (t, u) in SOURCES.items()},
        "briefing": blocks(briefing_blocks()),
        "further_reading": [list(p) for p in further_reading()],
        "simple": blocks(simple_blocks(cfg)),
        "derivations": [{"title": t, "blocks": blocks(b)}
                        for t, b in derivation_sections(cfg, example_row)],
        "derivation_example": {"scenario": example.scenario.title,
                               "t": DERIVATION_EXAMPLE[1]},
        "scenarios": {
            "voyage": [{"key": k, "title": s.title, "description": s.description,
                        "event_text": s.event_text} for k, s in VOYAGE_SCENARIOS.items()],
            "short": [{"key": k, "title": s.title, "description": s.description,
                       "event_text": s.event_text} for k, s in SCENARIOS.items()],
        },
    }


# ------------------------------------------------------- bridge view


def _signal(row) -> list:
    """C/N0 per satellite id 1..12 (None if not received)."""
    by_id = {s.id: r(s.cn0_dbhz, 1) for s in row.epoch.satellites}
    return [by_id.get(i) for i in range(1, SATELLITE_COUNT + 1)]


def _bitmask(indices) -> int:
    return sum(1 << i for i in indices)


def navigator_scenario(run: Run) -> dict:
    """Only what the bridge view shows: status, vitals, checks, the signal
    graph, the map and the chosen navigation aid."""
    full = scenario_payload(run)
    keep = ("meta", "state", "verdict", "lat", "lon", "unc", "heading", "speed", "nsat", "agc",
            "clean", "need", "glat", "glon", "tlat", "tlon", "gerr")
    payload = {k: full[k] for k in keep}
    payload["meta"]["solution"] = run.solution
    payload["cn0"] = [r(sum(c) / len(c), 1) if c else None
                      for c in ([s.cn0_dbhz for s in w.epoch.tracked] for w in run.rows)]
    payload["checks"] = [[c[:3] for c in row] for row in full["checks"]]
    payload["sig"] = [_signal(w) for w in run.rows]
    payload["trk"] = [_bitmask(s.id - 1 for s in w.epoch.tracked) for w in run.rows]
    payload["aid_used"] = [len(w.result.aux_used) for w in run.rows]
    payload["aid_offered"] = [len(w.aid.fixes) if w.aid else 0 for w in run.rows]
    if run.solution == "pseudolites":
        payload["stations"] = [_bitmask(w.aid.stations_heard) for w in run.rows]
    if run.solution == "peers":
        frame = run.frame
        payload["peers"] = [[[r(v, 6) for v in frame.to_latlon(x, y)] + [int(in_range)]
                             for x, y, in_range in w.aid.peers] for w in run.rows]
        payload["peers_used"] = [_bitmask(int(s.split(":")[1]) for s in w.result.aux_used)
                                 for w in run.rows]
    if run.solution == "seabed":
        payload["seabed"] = [_seabed_fix(run, w) for w in run.rows]
    return payload


def _finite(value: float, digits: int):
    return None if math.isinf(value) else r(value, digits)


def _seabed_fix(run: Run, row) -> object:
    """Per second: None (no attempt), 0 (attempt, no clear match) or
    [lat, lon, sigma east, sigma north (None = no information), accepted]."""
    if not row.aid or not row.aid.seabed_tried:
        return None
    if not row.aid.fixes:
        return 0
    fix = row.aid.fixes[0]
    lat, lon = run.frame.to_latlon(*fix.position)
    return [r(lat, 6), r(lon, 6), _finite(fix.sigma_m, 0), _finite(fix.sigma_north, 0),
            int("seabed" in row.result.aux_used)]


def accuracy_summary(run: Run) -> dict:
    """How close the ship's position was to the truth: during the event
    (plus two minutes of recovery), or over the whole run without an event."""
    sc = run.scenario
    rows = [w for w in run.rows if sc.event_start is None
            or sc.event_start <= w.t < sc.event_end + 120]
    errors = [w.guard_error for w in rows]
    within = sum(w.guard_error <= w.result.uncertainty_m for w in rows)
    return {"mean_m": r(sum(errors) / len(errors), 1), "worst_m": r(max(errors), 1),
            "within_pct": r(100.0 * within / len(rows), 0)}


def navigator_content(cfg: GuardConfig, content: dict, chart: dict, accuracy: dict) -> dict:
    return {
        "states": content["states"],
        "verdicts": content["verdicts"],
        "palette": content["palette"],
        "actions": {state: {k: a[k] for k in ("autopilot_mode", "recommended_speed_kn",
                                               "crew_instructions")}
                    for state, a in content["actions"].items()},
        "checks": [{"name": c["name"], "if_fails": CHECK_EXPLANATIONS[c["name"]]["if_fails"]}
                   for c in content["checks"]],
        "scenarios": content["scenarios"],
        "coast_lat_short": content["coast_lat_short"],
        "route_grid": chart["route"],
        "solutions": [{"key": k, "title": t} for k, t in SOLUTIONS.items()],
        "stations": [{"name": n, "lat": lat, "lon": lon} for n, lat, lon in PSEUDOLITE_SITES],
        "peers": [p[0] for p in PEERS],
        "accuracy": accuracy,
    }


def main() -> None:
    cfg = GuardConfig()
    shutil.rmtree(NAV_DATA / "scenarios", ignore_errors=True)  # drop files of old layouts
    comparison = {"voyage": [], "short": []}
    accuracy = {"voyage": {}, "short": {}}
    for mode, voyage, scenarios in (("voyage", True, VOYAGE_SCENARIOS),
                                    ("short", False, SCENARIOS)):
        for key in scenarios:
            run = run_scenario(key, voyage=voyage)
            comparison[mode].append(comparison_row(run))
            write_js(WEB_DATA / "scenarios" / f"{mode}_{key}.js",
                     f'MARINE.registerScenario("{mode}/{key}", "{packed(scenario_payload(run))}");')
            for solution in SOLUTIONS:
                aided = run if solution == "none" else run_scenario(key, voyage=voyage,
                                                                    solution=solution)
                accuracy[mode].setdefault(key, {})[solution] = accuracy_summary(aided)
                write_js(NAV_DATA / "scenarios" / f"{mode}_{key}_{solution}.js",
                         f'NAV.registerScenario("{mode}/{key}/{solution}", '
                         f'"{packed(navigator_scenario(aided))}");')
            print(f"exported {mode}/{key}")
            if voyage and key == "normal":
                chart = chart_payload(run)
                write_js(WEB_DATA / "chart.js", f'MARINE.registerChart("{packed(chart)}");')

    content = content_payload(cfg, run_scenario(DERIVATION_EXAMPLE[0], voyage=True))
    content["comparison"] = comparison
    # Short test runs use a straight synthetic coast at y = coast_y.
    content["coast_lat_short"] = run_scenario("normal").frame.to_latlon(0.0, cfg.coast_y)[0]
    write_js(WEB_DATA / "content.js",
             "MARINE.content = " + json.dumps(content, ensure_ascii=False, indent=1) + ";")
    write_js(NAV_DATA / "content.js",
             f'NAV.registerContent("{packed(navigator_content(cfg, content, chart, accuracy))}");')
    print(f"wrote {WEB_DATA} and {NAV_DATA}")


if __name__ == "__main__":
    main()
